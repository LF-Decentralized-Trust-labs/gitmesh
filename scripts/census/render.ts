/**
 * `stats.md`: the census statistics as tables, the appendix a census post
 * links to. Rendered from `stats.json` alone, so the two never disagree.
 */
import { RELATIONS, SURFACES, type CensusStats, type Relation, type Surface } from "./aggregate.js";

const SURFACE_HEADINGS: Record<Surface, string> = {
  instructions: "Instructions and rules",
  mcp: "MCP",
  skills: "Skills",
  commands: "Commands and subagents",
  settings: "Settings, hooks and plugins",
};

const RELATION_HEADINGS: Record<Relation, string> = {
  symlink: "Symlink",
  import: "`@AGENTS.md` import",
  identical: "Identical copy",
  diverged: "Diverged copy",
  pointer: "Pointer",
  separate: "Separate document",
  unreadable: "Unreadable",
};

const RELATION_DEFINITIONS: Record<Relation, string> = {
  symlink: "one file is a symlink to the other, or both link to one file: zero drift",
  import: "the file pulls `AGENTS.md` in with an `@AGENTS.md` line, in `CLAUDE.md` or `GEMINI.md`, whose agents expand imports",
  identical: "a separate file with the same content",
  diverged: "a copy that shares some content with `AGENTS.md` and differs in the rest",
  pointer:
    "shares nothing with `AGENTS.md`, and the shorter of the two files, at most three blocks, names the other: a line such as \"See AGENTS.md\"",
  separate: "shares nothing with `AGENTS.md`: a document of its own",
  unreadable: "a broken symlink, or content doctor could not read",
};

function percent(count: number, total: number): string {
  if (total === 0 || count === 0) return "0%";
  const value = (100 * count) / total;
  return value < 1 ? "<1%" : `${Math.round(value)}%`;
}

const compare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** Entries by descending count, then name: the order a reader scans a table in. */
function byCount<T>(record: Record<string, T>, count: (value: T) => number): Array<[string, T]> {
  return Object.entries(record).sort(([a, x], [b, y]) => count(y) - count(x) || compare(a, b));
}

const row = (cells: ReadonlyArray<string | number>): string => `| ${cells.join(" | ")} |`;
const header = (cells: readonly string[]): string[] => [row(cells), row(cells.map(() => "---"))];
const code = (text: string): string => `\`${text}\``;

export function renderStatsMarkdown(stats: CensusStats): string {
  const { edition, repositories, agents, instructions, drift, mcp, skills } = stats;
  const total = repositories.scanned;
  /** A table cell: `29 (73%)`. */
  const share = (count: number): string => `${count} (${percent(count, total)})`;
  /** In a sentence: `29 repositories (73%)`. */
  const repos = (count: number): string =>
    `${count} ${count === 1 ? "repository" : "repositories"} (${percent(count, total)})`;
  /** The verb form that agrees with `count`: `agree(1, "keeps", "keep")`. */
  const agree = (count: number, one: string, many: string): string => (count === 1 ? one : many);
  const lost = [
    repositories.unavailable > 0 ? `${repositories.unavailable} could no longer be fetched` : "",
    repositories.failed > 0 ? `${repositories.failed} failed` : "",
  ].filter(Boolean);

  const lines: string[] = [
    `# Agent configuration census ${edition.discoveredOn.slice(0, 7)}: statistics`,
    "",
    "Generated by `pnpm census aggregate`; do not edit by hand. The method, its definitions and how to " +
      "reproduce these numbers are in `scripts/census/README.md`.",
    "",
    `- **Repositories:** the ${repositories.selected} most-starred GitHub repositories matching ` +
      `${code(edition.search)} that have ${code(edition.requiredFile)} at the root of their default branch ` +
      `and a license GitHub can name, discovered ${edition.discoveredOn} and pinned to that day's ` +
      "default-branch commit.",
    `- **Scanned:** ${total}${lost.length > 0 ? `; ${lost.join(" and ")}` : ""}. Percentages are of the ${total}.`,
    `- **Doctor:** gitmesh-cli ${edition.gitmeshVersion}, repository files only: machine-level probes off, no \`--user\`.`,
    "",
    "## Agent-specific configuration",
    "",
    `${repos(agents.withOwnConfig)} ${agree(agents.withOwnConfig, "commits", "commit")} configuration for ` +
      "at least one specific agent besides `AGENTS.md`.",
    "",
    ...header(["Agents with configuration of their own", "Repositories"]),
    ...Object.entries(agents.perRepository).map(([count, repos]) =>
      row([count === "4+" ? "4 or more" : count, share(repos)]),
    ),
    "",
    ...header(["Agent", "Repositories", ...SURFACES.map((surface) => SURFACE_HEADINGS[surface])]),
    ...byCount(agents.byAgent, (counts) => counts.repositories).map(([agent, counts]) =>
      row([code(agent), share(counts.repositories), ...SURFACES.map((surface) => counts[surface])]),
    ),
    "",
  ];
  const shared = byCount(agents.sharedFiles, (count) => count);
  if (shared.length > 0) {
    lines.push(
      "Files that several agents read, counted for none of them above: " +
        `${shared.map(([path, count]) => `${code(path)} in ${repos(count)}`).join(", ")}.`,
      "",
    );
  }

  const relationTotals = Object.fromEntries(
    RELATIONS.map((relation) => [
      relation,
      Object.values(instructions.rootFiles).reduce((sum, counts) => sum + counts[relation], 0),
    ]),
  ) as Record<Relation, number>;
  lines.push(
    "## Root instruction files",
    "",
    `${repos(instructions.nestedAgentsMd)} also ${agree(instructions.nestedAgentsMd, "places", "place")} ` +
      `\`AGENTS.md\` files in subdirectories. ${repos(instructions.withAnotherRootFile)} ` +
      `${agree(instructions.withAnotherRootFile, "keeps", "keep")} at least one more root instruction file ` +
      "next to `AGENTS.md`; this is how each relates to it:",
    "",
    ...header(["File", "Repositories", ...RELATIONS.map((relation) => RELATION_HEADINGS[relation])]),
    ...byCount(instructions.rootFiles, (counts) => counts.repositories).map(([path, counts]) =>
      row([code(path), share(counts.repositories), ...RELATIONS.map((relation) => counts[relation])]),
    ),
    row([
      "All files",
      Object.values(instructions.rootFiles).reduce((sum, counts) => sum + counts.repositories, 0),
      ...RELATIONS.map((relation) => relationTotals[relation]),
    ]),
    "",
    ...RELATIONS.map((relation) => `- **${RELATION_HEADINGS[relation]}:** ${RELATION_DEFINITIONS[relation]}.`),
    "",
    `${repos(instructions.withDivergedCopy)} ${agree(instructions.withDivergedCopy, "has", "have")} at least ` +
      "one diverged copy. Doctor diffed two or more root instruction documents in " +
      `${repos(drift.compared)} and reported drift in ${repos(drift.drifting)}: its drift count includes ` +
      "pointers and separate documents, which it diffs as if they were copies.",
    "",
    "## MCP servers and skills",
    "",
    `- ${repos(mcp.repositories)} ${agree(mcp.repositories, "commits", "commit")} an MCP config file ` +
      "(`.mcp.json`, `.cursor/mcp.json`, `.vscode/mcp.json`, `.roo/mcp.json`, Antigravity `mcp_config.json`), " +
      `${mcp.severalAgents} of them for more than one agent. MCP servers declared inside ` +
      "`.codex/config.toml`, `opencode.json` or `.gemini/settings.json` are not counted here; GM005 below compares them all.",
    `- ${repos(skills.repositories)} ${agree(skills.repositories, "ships", "ship")} skills, ` +
      `${skills.severalAgents} of them for more than one agent. ${skills.sameSkillSeveralAgents} ` +
      `${agree(skills.sameSkillSeveralAgents, "keeps", "keep")} a skill of the same name in more than one ` +
      `agent's skills directory, and in ${skills.sameSkillCopied} of those at least two of the directories ` +
      "hold separate copies rather than a symlink.",
    "",
    "## Third-party managers",
    "",
  );
  const managers = byCount(stats.managers, (count) => count);
  if (managers.length === 0) {
    lines.push("No repository has files doctor labels as managed by another tool.", "");
  } else {
    lines.push(
      ...header(["Manager", "Repositories"]),
      ...managers.map(([manager, count]) => row([code(manager), share(count)])),
      "",
      "`symlinks` counts repositories in which a known agent config path is a symlink.",
      "",
    );
  }
  lines.push(
    "## Doctor findings",
    "",
    ...header(["Rule", "Severity", "Repositories", "Findings"]),
    ...Object.entries(stats.findings).map(([rule, { severity, repositories: repos, findings }]) =>
      row([rule, severity, share(repos), findings]),
    ),
    "",
    "## Scores",
    "",
    `Median score: ${stats.scores.median}/100.`,
    "",
    ...header(["Score", "Repositories"]),
    ...Object.entries(stats.scores.buckets).map(([bucket, count]) => row([bucket, share(count)])),
  );
  return `${lines.join("\n")}\n`;
}
